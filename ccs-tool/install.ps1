#Requires -Version 5.1
<#
.SYNOPSIS
    ccs-tool 安装脚本（Windows 原生，无需管理员权限，可重复执行 / 幂等）。

.DESCRIPTION
    步骤：
      1. 检查 python（需要 3.10+，只依赖标准库）
      2. 在 %USERPROFILE%\.ccs\bin 生成 ccs.cmd 启动器（shim），指向本目录的 ccs.py
      3. 把该 bin 目录加入“当前用户”PATH（已包含则跳过）
      4. 可选 -Autostart：运行 python ccs.py autostart on 注册开机自启

    本脚本只改“当前用户”的 PATH，不写系统级环境变量，不请求管理员权限。
    重复运行是安全的：shim 会被覆盖重写，PATH 不会重复追加。

.PARAMETER Autostart
    同时开启开机自启（登录时自动 daemon start --restore）。

.EXAMPLE
    powershell -NoProfile -ExecutionPolicy Bypass -File .\install.ps1

.EXAMPLE
    powershell -NoProfile -ExecutionPolicy Bypass -File .\install.ps1 -Autostart
#>
[CmdletBinding()]
param(
    [switch]$Autostart
)

$ErrorActionPreference = 'Stop'

$script:DoneList = New-Object System.Collections.Generic.List[string]
$script:WarnList = New-Object System.Collections.Generic.List[string]
$script:PathReady = $false

function Add-Done {
    param([string]$Text)
    Write-Host "[ OK ] $Text" -ForegroundColor Green
    $script:DoneList.Add($Text) | Out-Null
}
function Add-Warn {
    param([string]$Text)
    Write-Host "[WARN] $Text" -ForegroundColor Yellow
    $script:WarnList.Add($Text) | Out-Null
}
function Add-Info {
    param([string]$Text)
    Write-Host "       $Text" -ForegroundColor DarkGray
}

Write-Host "== ccs-tool 安装 ==" -ForegroundColor Cyan

# ---------- 0. 定位源码目录与状态目录 ----------
$srcDir = $PSScriptRoot
if ([string]::IsNullOrWhiteSpace($srcDir)) { $srcDir = (Get-Location).Path }
$ccsPy = Join-Path $srcDir 'ccs.py'
if ([string]::IsNullOrWhiteSpace($env:CCS_HOME)) {
    $ccsHome = Join-Path $env:USERPROFILE '.ccs'
} else {
    $ccsHome = $env:CCS_HOME
}
$binDir = Join-Path $ccsHome 'bin'
$shimPath = Join-Path $binDir 'ccs.cmd'

Add-Info "源码目录 : $srcDir"
Add-Info "状态目录 : $ccsHome"

# ---------- 1. 检查 python ----------
$pythonCmd = Get-Command python -ErrorAction SilentlyContinue
if ($null -eq $pythonCmd) {
    Add-Warn "未找到 python。请先安装 Python 3.10+，并确保 python 在 PATH 中。"
    Add-Info "下载: https://www.python.org/downloads/windows/"
    exit 1
}

$pyVer = ''
try {
    $pyVer = (& python -c "import sys; print('%d.%d' % sys.version_info[:2])" 2>&1 | Out-String).Trim()
} catch {
    $pyVer = ''
}
if ($pyVer -notmatch '^\d+\.\d+$') {
    Add-Warn "python 无法正常执行（输出: $pyVer）。"
    Add-Info "若这是 Microsoft Store 的 python 别名占位符（WindowsApps\python.exe），请安装官方 Python 并关闭“应用执行别名”。"
    exit 1
}
if ([version]$pyVer -lt [version]'3.10') {
    Add-Warn "python 版本为 $pyVer，需要 3.10 或更高版本。"
    exit 1
}
Add-Done "python $pyVer 可用（$($pythonCmd.Source)）"

if (Test-Path -LiteralPath $ccsPy) {
    Add-Done "找到 $ccsPy"
} else {
    Add-Warn "未找到 $ccsPy（shim 仍会指向该路径）。请把本脚本放在 ccs-tool 源码目录内运行。"
}

# ---------- 2. 生成 ccs.cmd 启动器（shim） ----------
try {
    if (-not (Test-Path -LiteralPath $binDir)) {
        New-Item -ItemType Directory -Force -Path $binDir | Out-Null
    }
    $shimLines = @(
        '@echo off',
        'rem ccs-tool launcher shim, generated by install.ps1',
        'rem rerun install.ps1 in the source tree to regenerate',
        'chcp 65001 >nul',
        ('python "' + $ccsPy + '" %*')
    )
    $shimText = ($shimLines -join [Environment]::NewLine) + [Environment]::NewLine
    $utf8NoBom = New-Object System.Text.UTF8Encoding($false)
    [System.IO.File]::WriteAllText($shimPath, $shimText, $utf8NoBom)
    Add-Done "已生成启动器: $shimPath"
} catch {
    Add-Warn "生成 $shimPath 失败: $($_.Exception.Message)"
    exit 1
}

# ---------- 3. 把 bin 目录加入用户 PATH ----------
$binNorm = $binDir.TrimEnd('\')
$userPath = [Environment]::GetEnvironmentVariable('Path', 'User')
if ($null -eq $userPath) { $userPath = '' }
$alreadyInPath = $false
foreach ($p in ($userPath -split ';')) {
    if ($p.Trim().TrimEnd('\') -ieq $binNorm) { $alreadyInPath = $true; break }
}
if ($alreadyInPath) {
    Add-Done "用户 PATH 已包含 $binDir（保持原样）"
    $script:PathReady = $true
} else {
    try {
        $trimmed = $userPath.TrimEnd(';')
        if ($trimmed -eq '') { $newPath = $binDir }
        else { $newPath = $trimmed + ';' + $binDir }
        [Environment]::SetEnvironmentVariable('Path', $newPath, 'User')
        if ($newPath.Length -gt 1800) {
            Add-Warn "用户 PATH 已较长（$($newPath.Length) 字符），极少数情况下系统会截断，请自行检查。"
        }
        Add-Done "已把 $binDir 加入用户 PATH（新开的终端生效）"
        $script:PathReady = $true
    } catch {
        Add-Warn "写入用户 PATH 失败: $($_.Exception.Message)"
    }
}
# 让当前会话也立即可以使用 ccs
$env:Path = $binDir + ';' + $env:Path

# ---------- 4. 可选：开机自启 ----------
if ($Autostart) {
    if (-not (Test-Path -LiteralPath $ccsPy)) {
        Add-Warn "跳过开机自启：找不到 $ccsPy"
    } else {
        try {
            $autoOut = (& python $ccsPy autostart on 2>&1 | Out-String).Trim()
            if ($LASTEXITCODE -eq 0) {
                Add-Done "已开启开机自启（python ccs.py autostart on）"
                if ($autoOut -ne '') { Add-Info $autoOut }
            } else {
                Add-Warn "autostart on 失败（exit $LASTEXITCODE）: $autoOut"
            }
        } catch {
            Add-Warn "autostart on 异常: $($_.Exception.Message)"
        }
    }
} else {
    Add-Info "未指定 -Autostart，跳过开机自启（可随时运行: ccs autostart on）"
}

# ---------- 5. 汇总 ----------
Write-Host ""
Write-Host "== 安装结果 ==" -ForegroundColor Cyan
Write-Host "已完成的步骤:"
foreach ($d in $script:DoneList) {
    Write-Host ("  [OK]   " + $d) -ForegroundColor Green
}
if ($script:WarnList.Count -gt 0) {
    Write-Host "警告:"
    foreach ($w in $script:WarnList) {
        Write-Host ("  [WARN] " + $w) -ForegroundColor Yellow
    }
}
Write-Host ""
Write-Host "下一步:"
if ($script:PathReady) {
    Write-Host "  1) 重新打开一个终端（让用户 PATH 生效）"
} else {
    Write-Host "  1) 用户 PATH 未写入成功（可能受权限/策略限制），请把下面目录手动加入“用户变量 Path”：" -ForegroundColor Yellow
    Write-Host ("     " + $binDir) -ForegroundColor Yellow
}
Write-Host "  2) 启动守护进程: ccs daemon start"
Write-Host "  3) 新建会话    : ccs new myclaude -- claude"
Write-Host "  4) 查看会话    : ccs ls"
Write-Host "  5) 开机自启    : ccs autostart on"
Write-Host ""
if ($script:WarnList.Count -eq 0) {
    Write-Host "安装完成（全部步骤成功）。" -ForegroundColor Green
} else {
    Write-Host "安装完成（有 $($script:WarnList.Count) 条警告，见上）。" -ForegroundColor Yellow
}
exit 0
